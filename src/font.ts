export function glyphFor(character: string): Glyph {
  return GLYPHS[character.toUpperCase()] ?? [".....", ".....", ".....", ".....", ".....", ".....", "....."];
}

export function renderWord(text: string, spacing = 1): boolean[][] {
  const normalized = text.trim().toUpperCase();
  const rows = Array.from({ length: FONT_HEIGHT }, () => [] as boolean[]);

  for (let charIndex = 0; charIndex < normalized.length; charIndex += 1) {
    const glyph = glyphFor(normalized[charIndex] ?? "");
    for (let row = 0; row < FONT_HEIGHT; row += 1) {
      for (const cell of glyph[row] ?? "") rows[row]!.push(cell === "#");
      if (charIndex < normalized.length - 1) {
        for (let gap = 0; gap < spacing; gap += 1) rows[row]!.push(false);
      }
    }
  }
  return rows;
}
